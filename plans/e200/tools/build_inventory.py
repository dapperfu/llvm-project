"""Build plans/e200/instruction-inventory.yaml (deliverable C).

Inputs:
  * vlepem-table-b2.yaml  - VLEPEM Rev. 0 Table B-2 rows (extract_vle_table.py)
  * core-extras.yaml      - instructions documented only by core manuals
  * capability-matrix.yaml - per-core category statuses and exceptions

Every output record gets a per-core availability map whose values are
supported / unsupported / unverified, derived from the record's category and
any per-mnemonic exception in the capability matrix.  Implementation and test
status start as "pending" and are updated by later milestones.
"""

from __future__ import annotations

from pathlib import Path

import click
import yaml

CORES = [
    "e200z0",
    "e200z0h",
    "e200z1",
    "e200z3",
    "e200z446n3",
    "e200z6",
    "e200z759n3",
    "e200z760n3",
]


def resolve_core(matrix: dict, core: str) -> dict:
    """Return a core entry with `inherits` applied."""
    entry = dict(matrix["cores"][core])
    parent = entry.get("inherits")
    if parent:
        merged = resolve_core(matrix, parent)
        merged.update({k: v for k, v in entry.items() if k != "inherits"})
        return merged
    return entry


def base_mnemonic(mnemonic: str) -> str:
    """Strip optional suffix markers such as [o][.] and [l]."""
    out = mnemonic
    for marker in ("[o]", "[.]", "[l]"):
        out = out.replace(marker, "")
    return out


def availability(core_entry: dict, record: dict) -> dict:
    """Compute {status, cite} for one record on one core."""
    mnem = base_mnemonic(record["mnemonic"])
    exceptions = core_entry.get("exceptions", {})
    if mnem in exceptions:
        return dict(exceptions[mnem])
    explicit = record.get("cores")
    if explicit is not None:
        if core_entry["_name"] in explicit:
            return {"status": "supported", "cite": "core-extras.yaml"}
        return {"status": "unverified", "cite": "not documented for this core"}
    if record["mode"] == "vle" and core_entry["isa"]["vle"] != "supported":
        return {"status": core_entry["isa"]["vle"], "cite": "VLE category"}
    if record["mode"] == "booke" and core_entry["isa"]["booke_encoding"] != "supported":
        return {"status": "unsupported", "cite": "no Book E encodings"}
    cat = core_entry.get("categories", {}).get(record["category"])
    if cat is None:
        return {"status": "unverified", "cite": f"category {record['category']} not in matrix"}
    return dict(cat)


def build(table: list[dict], extras: list[dict], matrix: dict) -> list[dict]:
    """Merge inputs into inventory records."""
    cores = {}
    for name in CORES:
        entry = resolve_core(matrix, name)
        entry["_name"] = name
        cores[name] = entry
    records = []
    for rec in table + extras:
        out = {k: v for k, v in rec.items() if k != "cores"}
        out["id"] = f"{base_mnemonic(rec['mnemonic'])}@{rec['opcode_hex']}"
        out["cores"] = {name: availability(entry, rec) for name, entry in cores.items()}
        out["llvm_record"] = None
        out["impl_status"] = "pending"
        out["tests"] = {
            "enc": "pending",
            "dis": "pending",
            "roundtrip": "pending",
            "neg": "pending",
        }
        records.append(out)
    return records


@click.command()
@click.option("--table", type=click.Path(exists=True, path_type=Path), required=True)
@click.option("--extras", type=click.Path(exists=True, path_type=Path), required=True)
@click.option("--matrix", type=click.Path(exists=True, path_type=Path), required=True)
@click.option("--output", type=click.Path(dir_okay=False, path_type=Path), required=True)
def main(table: Path, extras: Path, matrix: Path, output: Path) -> None:
    """Write the instruction inventory YAML."""
    records = build(
        yaml.safe_load(table.read_text()),
        yaml.safe_load(extras.read_text()),
        yaml.safe_load(matrix.read_text()),
    )
    header = (
        "# Generated by plans/e200/tools/build_inventory.py; edit the inputs, not this file.\n"
        "# Fields: id, mnemonic, form, opcode_hex, width, mode (vle|shared|booke|both),\n"
        "# mode_dependency, privilege, category, description, sources, cores (per-core\n"
        "# status + citation), llvm_record, impl_status, tests (enc/dis/roundtrip/neg).\n"
    )
    output.write_text(header + yaml.safe_dump(records, sort_keys=False, width=100))
    summary: dict[str, dict[str, int]] = {c: {} for c in CORES}
    for rec in records:
        for core, avail in rec["cores"].items():
            summary[core][avail["status"]] = summary[core].get(avail["status"], 0) + 1
    click.echo(f"{len(records)} records")
    for core, counts in summary.items():
        click.echo(f"  {core}: {counts}")


if __name__ == "__main__":
    main()
