"""Generate llvm/lib/Target/PowerPC/PPCInstrVLEShared.td.

VLEPEM Rev. 0 Table B-2 lists the Book E instructions that keep their
encodings in VLE mode ("shared" rows).  This tool matches every 32-bit PPC
instruction record from `llvm-tblgen --dump-json` against those rows by
encoding: a record is shared when all opcode bits of a row are fixed in the
record and equal to the row's opcode.  The opcode mask comes from the
instruction form; bits named by the `[o]` and `[.]` mnemonic suffixes are left
out so that every OE/Rc variant matches.

Usage:
  llvm-tblgen -I llvm/include -I llvm/lib/Target/PowerPC \\
      llvm/lib/Target/PowerPC/PPC.td --dump-json -o ppc.json
  python gen_vle_shared.py --table ../vlepem-table-b2.yaml --records ppc.json \\
      --output ../../../llvm/lib/Target/PowerPC/PPCInstrVLEShared.td
"""

from __future__ import annotations

import json
from pathlib import Path

import click
import yaml

HEADER = """\
//===-- PPCInstrVLEShared.td - Book E instructions valid in VLE mode ------===//
//
// Part of the LLVM Project, under the Apache License v2.0 with LLVM Exceptions.
// See https://llvm.org/LICENSE.txt for license information.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
//
//===----------------------------------------------------------------------===//
//
// Book E instructions whose encodings VLEPEM Rev. 0 Table B-2 lists as
// available in VLE mode.  Generated by plans/e200/tools/gen_vle_shared.py;
// regenerate rather than edit.
//
//===----------------------------------------------------------------------===//

"""


def bit(n: int) -> int:
    """Mask for big-endian instruction bit n (bit 0 is the MSB)."""
    return 1 << (31 - n)


def field(first: int, last: int) -> int:
    mask = 0
    for n in range(first, last + 1):
        mask |= bit(n)
    return mask


PRIMARY = field(0, 5)


def opcode_mask(row: dict) -> int:
    """Opcode bits of a Table B-2 row, from its primary opcode and form."""
    mnemonic = row["mnemonic"]
    value = int(row["opcode_hex"], 16)
    form = row["form"]
    if value >> 26 == 4:
        # SPE, EFPU and AltiVec forms.
        if form == "VA":
            mask = PRIMARY | field(26, 31)
        elif form == "VC":
            mask = PRIMARY | field(21, 31)
        elif form == "EVSEL":
            mask = PRIMARY | field(21, 28)
        else:
            mask = PRIMARY | field(21, 31)
        if "[.]" in mnemonic:
            mask &= ~bit(21)
        return mask
    assert value >> 26 == 31, f"unexpected primary opcode in {mnemonic}"
    if form == "A":
        mask = PRIMARY | field(26, 31)
    else:
        # X, XO, XFX: the extended opcode is in bits 21-30 (22-30 plus OE for
        # XO).  Table B-2 gives "D" for xor[.], an extraction error; the
        # opcode is X-form.
        mask = PRIMARY | field(21, 31)
    if "[o]" in mnemonic:
        mask &= ~bit(21)
    if "[.]" in mnemonic:
        mask &= ~bit(31)
    return mask


def row_opcode(row: dict) -> int:
    """Opcode of a Table B-2 row, with the efs* erratum corrected.

    VLEPEM Rev. 0 Table B-2 gives the efs* (SP.FS) rows the extended opcodes
    of the matching efd* instructions (0x2E0-0x2FF); SPEPEM Rev. 0 Table
    (EFX opcodes) places them 0x20 lower (efsabs 0x2C4).
    """
    value = int(row["opcode_hex"], 16)
    if row["mnemonic"].startswith("efs") and 0x2E0 <= value & 0x7FF <= 0x2FF:
        value -= 0x20
    return value


def fixed_bits(inst: list) -> tuple[int, int]:
    """Return (value, mask) of the literal bits of a TableGen Inst field."""
    value = mask = 0
    for n, b in enumerate(inst):
        if isinstance(b, int):
            mask |= bit(n)
            value |= b << (31 - n)
    return value, mask


@click.command()
@click.option("--table", type=click.Path(exists=True, path_type=Path), required=True)
@click.option("--records", type=click.Path(exists=True, path_type=Path), required=True)
@click.option("--output", type=click.Path(dir_okay=False, path_type=Path), required=True)
def main(table: Path, records: Path, output: Path) -> None:
    rows = [r for r in yaml.safe_load(table.read_text()) if r["mode"] == "shared"]
    patterns = [(row_opcode(r), opcode_mask(r), r["mnemonic"]) for r in rows]
    dump = json.loads(records.read_text())

    # Each record is credited to its most specific matching rows; VA-form rows
    # (opcode in bits 26-31 only) otherwise also match SPE encodings.  Ties
    # are real: AltiVec and SPE share encodings (vnor and evmhousiaaw).
    shared: dict[str, tuple[int, list[str]]] = {}
    for name in dump["!instanceof"]["Instruction"]:
        rec = dump[name]
        inst = rec.get("Inst")
        if rec.get("Namespace") != "PPC" or rec.get("isPseudo") or rec.get("Size") != 4:
            continue
        if rec.get("DecoderNamespace") == "VLE" or not isinstance(inst, list) or len(inst) != 32:
            continue
        value, mask = fixed_bits(inst)
        for row_value, row_mask, mnemonic in patterns:
            # Bit 31 is reserved in many X forms; some records leave it unset.
            required = row_mask & ~bit(31)
            compared = row_mask & mask
            if mask & required == required and value & compared == row_value & compared:
                specificity = row_mask.bit_count()
                if name not in shared or shared[name][0] < specificity:
                    shared[name] = (specificity, [mnemonic])
                elif shared[name][0] == specificity:
                    shared[name][1].append(mnemonic)

    lines = [HEADER]
    for name in sorted(shared):
        lines.append(f"def : VLESharedInst<{name}>; // {' '.join(shared[name][1])}\n")
    output.write_text("".join(lines))
    matched_rows = {m for _, mnemonics in shared.values() for m in mnemonics}

    unmatched = sorted({m for _, _, m in patterns} - matched_rows)
    click.echo(f"{len(shared)} records match {len(matched_rows)} of {len(patterns)} rows")
    click.echo("rows without an LLVM instruction: " + " ".join(unmatched))


if __name__ == "__main__":
    main()
